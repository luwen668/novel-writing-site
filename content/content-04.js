<p>角色声音跑偏的头号原因，是所有人都染上了作者的腔调：都用一样文雅的书面语，都抖一样的机灵，都发出一样的感慨。自检办法是“遮名检验”——把一段对话的人名全部遮住，逐句猜是谁说的：猜得出的留，猜不出的重写。更狠的进阶版：遮住名字后念给旁人听，请他猜人物的职业和年龄。声纹不漂移还有一个工程技巧：动笔前给每个主要角色建一张“语言档案卡”，写下他的口头禅三条、爱用的句式、绝不说的话、说话时的身体习惯（摸鼻子、敲桌子），写作时贴在手边对照。</p>
